"""Generation of explicit Python Appium scripts."""

from __future__ import annotations

from collections.abc import Iterable

from c4.schemas import SynthStep
from c4.synthesis.locators import to_appium_locator


class AppiumScriptGenerator:
    """Render validated synthesis steps into explicit Appium statements."""

    def generate(
        self,
        steps: Iterable[SynthStep],
        *,
        appium_url: str = "http://127.0.0.1:4723",
        capabilities: dict[str, object] | None = None,
    ) -> str:
        """Return deterministic, compilable Python source."""
        step_list = list(steps)
        caps = capabilities or {
            "platformName": "Android",
            "automationName": "UiAutomator2",
        }
        lines = [
            '"""Generated by HEART Component 4 test synthesis."""',
            "",
            "from __future__ import annotations",
            "",
            "import json",
            "import os",
            "from pathlib import Path",
            "",
            "from appium import webdriver",
            "from appium.options.android import UiAutomator2Options",
            "from appium.webdriver.common.appiumby import AppiumBy",
            "",
            f"APPIUM_URL = {appium_url!r}",
            f"CAPABILITIES = {caps!r}",
            f"STEP_ACTIONS = {tuple(step.action for step in step_list)!r}",
            "",
            "def _record_failure(driver, index: int, action: str, exc: Exception) -> None:",
            '    run_dir = Path(os.environ.get("C4_RUN_DIR", "."))',
            "    run_dir.mkdir(parents=True, exist_ok=True)",
            "    failure = {",
            '        "step_index": index,',
            '        "action": action,',
            '        "exception_type": type(exc).__name__,',
            '        "message": str(exc)[:500],',
            "    }",
            "    try:",
            '        (run_dir / "failure.json").write_text(json.dumps(failure, sort_keys=True), encoding="utf-8")',
            "    except Exception:",
            "        pass",
            "    try:",
            '        (run_dir / "page_source.xml").write_text(driver.page_source, encoding="utf-8")',
            "    except Exception:",
            "        pass",
            "    try:",
            '        driver.get_screenshot_as_file(str(run_dir / "screenshot.png"))',
            "    except Exception:",
            "        pass",
            "",
        ]
        for step in step_list:
            lines.append(f"def step_{step.index}(driver) -> None:")
            lines.extend(_render_step(step))
            lines.append("")
        lines.append(f"STEPS = ({', '.join(f'step_{step.index}' for step in step_list)}{',' if step_list else ''})")
        lines.extend(
            [
                "",
                "def run_test() -> None:",
                "    options = UiAutomator2Options().load_capabilities(CAPABILITIES)",
                "    driver = webdriver.Remote(APPIUM_URL, options=options)",
                "    driver.implicitly_wait(10)",
                "    try:",
                "        for index, step in enumerate(STEPS):",
                "            try:",
                "                step(driver)",
                "            except Exception as exc:",
                "                _record_failure(driver, index, STEP_ACTIONS[index], exc)",
                "                raise",
                "    finally:",
                "        driver.quit()",
                "",
                'if __name__ == "__main__":',
                "    run_test()",
                "",
            ]
        )
        return "\n".join(lines)


def _render_step(step: SynthStep) -> list[str]:
    if step.action in {"tap", "navigate", "input"}:
        strategy, value = to_appium_locator(step.target)
        locator = f"AppiumBy.{strategy}, {value!r}"
        statement = f"driver.find_element({locator})"
        if step.action == "input":
            statement += f".send_keys({step.value!r})"
        else:
            statement += ".click()"
        return [f"    {statement}"]
    if step.action == "back":
        return ["    driver.back()"]
    if step.action == "scroll":
        return [
            '    driver.execute_script("mobile: scrollGesture", {',
            '        "left": 100, "top": 300, "width": 600, "height": 1000,',
            '        "direction": "down", "percent": 0.75,',
            "    })",
        ]
    raise ValueError(f"Unsupported synthesized action: {step.action}")
